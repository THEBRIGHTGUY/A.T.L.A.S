// Minimal driver for the Heltec V4's built-in 0.96" OLED (SSD1306, 128 x 64, I2C). No library needed.
// The screen sits on its own I2C pins (Wire1), so it never disturbs the sensors on Wire.
#pragma once
#include <Wire.h>
#include "qr_v2.h"

#define OLED_SDA  17
#define OLED_SCL  18
#define OLED_RST  21
#define OLED_VEXT 36     // powers the screen; the code tries LOW then HIGH, so either board revision works
#define OLED_ADDR 0x3C
#define OLED_FLIP 1      // if the picture is upside down, change 1 to 0

static uint8_t oledBuf[128 * 8];   // one bit per pixel

// 5 x 7 font: capital letters, digits and a few symbols (lower case is shown as capitals)
