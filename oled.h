static void oledCmd(uint8_t c) {
  Wire1.beginTransmission(OLED_ADDR);
  Wire1.write((uint8_t)0x00);
  Wire1.write(c);
  Wire1.endTransmission();
}

static bool oledProbe() {
  Wire1.beginTransmission(OLED_ADDR);
  return Wire1.endTransmission() == 0;
}

static void oledPower(int level) {
  pinMode(OLED_VEXT, OUTPUT); digitalWrite(OLED_VEXT, level); delay(60);
  pinMode(OLED_RST, OUTPUT); digitalWrite(OLED_RST, LOW); delay(20); digitalWrite(OLED_RST, HIGH); delay(20);
}

static void oledShow() {
  oledCmd(0x21); oledCmd(0); oledCmd(127);   // columns 0..127
  oledCmd(0x22); oledCmd(0); oledCmd(7);     // pages 0..7
  for (int i = 0; i < 128 * 8; i += 16) {
    Wire1.beginTransmission(OLED_ADDR);
    Wire1.write((uint8_t)0x40);
    Wire1.write(oledBuf + i, 16);
    Wire1.endTransmission();
  }
}

static void oledClear() { memset(oledBuf, 0, sizeof oledBuf); }
static void oledOff()  { oledCmd(0xAE); }
static void oledWake() { oledCmd(0xAF); }

static bool oledBegin() {
  Wire1.begin(OLED_SDA, OLED_SCL);
  Wire1.setClock(400000);
  oledPower(LOW);                                       // Vext is active LOW on the V3 ...
  if (!oledProbe()) { oledPower(HIGH); if (!oledProbe()) return false; }   // ... and tried the other way round if needed
  const uint8_t init[] = {0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x00,
                          (uint8_t)(OLED_FLIP ? 0xA1 : 0xA0), (uint8_t)(OLED_FLIP ? 0xC8 : 0xC0),
                          0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF};
  for (uint8_t c : init) oledCmd(c);
  oledClear();
  oledShow();
  return true;
}

// ---------------------------------------------------------------- drawing
static void oledPixel(int x, int y, bool on) {
  if ((unsigned)x >= 128 || (unsigned)y >= 64) return;
  uint8_t m = 1 << (y & 7);
  uint8_t &b = oledBuf[x + (y >> 3) * 128];
  if (on) b |= m; else b &= ~m;
}

static void oledFill(int x, int y, int w, int h, bool on = true) {
  for (int j = 0; j < h; j++) for (int i = 0; i < w; i++) oledPixel(x + i, y + j, on);
}

static void oledFrame(int x, int y, int w, int h) {
  oledFill(x, y, w, 1); oledFill(x, y + h - 1, w, 1); oledFill(x, y, 1, h); oledFill(x + w - 1, y, 1, h);
}

static int oledTextWidth(const char *s, int size = 1) { int n = (int)strlen(s); return n ? n * 6 * size - size : 0; }

static void oledText(int x, int y, const char *s, int size = 1, bool on = true) {
  for (; *s; s++, x += 6 * size) {
    char c = *s; if (c >= 'a' && c <= 'z') c -= 32;
    const char *p = strchr(FONT_CHARS, c);
    const uint8_t *g = FONT[p ? p - FONT_CHARS : strchr(FONT_CHARS, '?') - FONT_CHARS];
    for (int col = 0; col < 5; col++) for (int row = 0; row < 7; row++)
      if ((g[col] >> row) & 1) oledFill(x + col * size, y + row * size, size, size, on);
  }
}

static void oledCenter(int y, const char *s, int size = 1) { oledText((128 - oledTextWidth(s, size)) / 2, y, s, size); }
static void oledRight(int y, const char *s, int size = 1)  { oledText(128 - oledTextWidth(s, size), y, s, size); }

// QR code drawn the way phones expect it: dark modules on a lit (white) square with a quiet border.
static void oledQR(const QrCode &q, int x0, int y0, int scale, int quiet) {
  int side = QR_SIZE * scale + 2 * quiet;
  oledFill(x0, y0, side, side, true);
  for (int y = 0; y < QR_SIZE; y++) for (int x = 0; x < QR_SIZE; x++)
    if (q.m[y][x]) oledFill(x0 + quiet + x * scale, y0 + quiet + y * scale, scale, scale, false);
}
